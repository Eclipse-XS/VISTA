    v.validation_id,
    v.sample_pk,
    s.sample_key,
    s.category_name,
    s.split,
    s.defect_type,
    v.run_id,
    v.validation_version,
    v.validation_status AS status,
    v.rgb_present,
    v.xyz_present,
    v.gt_present,
    v.rgb_decoded,
    v.xyz_decoded,
    v.gt_decoded,
    v.rgb_height,
    v.rgb_width,
    v.rgb_channels,
    v.rgb_dtype,
    v.xyz_height,
    v.xyz_width,
    v.xyz_channels,
    v.xyz_dtype,
    v.spatial_aligned,
    v.nan_3d_count,
    v.inf_3d_count,
